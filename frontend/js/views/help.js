export function renderHelp() {
  const el = document.getElementById('view-help');
  el.innerHTML = `
  <div class="page-head">
    <div>
      <p class="eyebrow">Руководство пользователя</p>
      <h1>Как это <span class="g">работает</span></h1>
      <p class="lede">Девять коротких разделов: что делает система, что означает каждый элемент
      экрана, как настраивать правила и где менять код. Читается за пять минут.</p>
    </div>
    <div class="head-actions">
      <input type="text" id="helpSearch" placeholder="Поиск по руководству…" style="min-width:220px">
      <a class="btn" href="/sa-docs/10-manual.md" download>Скачать .md</a>
      <button class="btn" onclick="window.print()">Печать</button>
    </div>
  </div>
  <div class="docs">
    <nav class="help-toc docsnav">
      ${SECTIONS.map(s => `<a data-goto="${s.id}">${esc(s.title)}</a>`).join('')}
    </nav>
    <div class="help-body">
      ${SECTIONS.map(s => `<section class="help-card" id="help-${s.id}" data-text="${esc(s.title.toLowerCase())}">
        <h2>${esc(s.title)}</h2>${s.html}</section>`).join('')}
    </div>
  </div>`;

  el.querySelectorAll('[data-goto]').forEach(a => a.onclick = () => {
    document.getElementById('help-' + a.dataset.goto)?.scrollIntoView({ behavior: 'smooth', block: 'start' });
    el.querySelectorAll('[data-goto]').forEach(x => x.classList.toggle('on', x === a));
  });

  const search = el.querySelector('#helpSearch');
  search.oninput = () => {
    const q = search.value.trim().toLowerCase();
    el.querySelectorAll('.help-card').forEach(card => {
      const hit = !q || card.textContent.toLowerCase().includes(q);
      card.style.display = hit ? '' : 'none';
    });
    el.querySelectorAll('[data-goto]').forEach(a => {
      const card = document.getElementById('help-' + a.dataset.goto);
      a.style.display = card && card.style.display === 'none' ? 'none' : '';
    });
  };
}